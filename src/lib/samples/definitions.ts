// SYNTHETIC demonstration data. Every vehicle, VIN, company and document here
// is fictional. One definition drives three things:
//   1. scripts/generate-samples.ts renders the actual PDF/PNG files in /samples
//   2. demo-mode "fixture" extractions (labelled as such in the UI)
//   3. ground truth for the evaluation script
import type { ClaimStated, ClaimType, FieldName, Odometer, Provenance, Status, Vehicle } from "../types";

export interface Citation {
  page: number;
  quote: string;
  /** Illustrative confidence for demo fixtures (not a model output). */
  confidence: number;
  /** Photos only: where the value is, [ymin, xmin, ymax, xmax] scaled 0–1000. */
  box?: [number, number, number, number];
}

export interface SampleDoc {
  id: string;
  filename: string;
  format: "pdf" | "png" | "jpg";
  provenance: Provenance;
  /** PDF: lines per page. "# " = heading, "" = spacer. PNG: unused. */
  pages: string[][];
  /** Dashboard photos only. `pastedOdometerText` simulates a retouched reading pasted over the original. */
  photo?: { odometerText: string; overlay: string; pastedOdometerText?: string };
  /** Sign the rendered PDF with this demo signer (generated by scripts/generate-samples.ts). */
  signedBy?: string;
  /** Edits made after rendering and signing: a white box over `from` on `line`, with `to` typed on top. */
  edits?: { line: string; from: string; to: string }[];
  /** Draw `value` on `line` in Courier, as an editor's substitute font would. */
  monoValue?: { line: string; value: string };
  truth: Partial<Record<FieldName, string | number | Odometer>>;
  cite: Partial<Record<FieldName, Citation>>;
}

export interface SampleCase {
  id: string;
  caseNumber: string;
  vehicle: Vehicle;
  createdAt: string;
  summary: string;
  docs: SampleDoc[];
  /** Expected rule outcome by finding id; used by tests and evaluation. */
  expected: Record<string, Status>;
  /** The seller's listing text, as pasted by the reviewer. */
  listing?: string;
  /** Seller claims parsed from the listing. */
  claims?: { type: ClaimType; stated: ClaimStated; sourceText: string }[];
  /** Expected claim status by claim type; used by tests and evaluation. */
  expectedClaims?: Partial<Record<ClaimType, Status>>;
  /** Field-level forensic indicators this case is built to trigger, as "sample doc id:field:code". Empty for clean cases. */
  expectedTamper?: string[];
}

