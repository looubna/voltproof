/** All text visible in a sample document (for checking that quotes really appear). */
export function sampleText(doc: SampleDoc): string[] {
  if (doc.format !== "pdf") return [[BANNER, doc.photo!.pastedOdometerText ?? doc.photo!.odometerText, doc.photo!.overlay].join("\n")];
  // What a reader sees: after any cover-and-retype edits.
  const edited = (l: string) => (doc.edits ?? []).reduce((acc, e) => (acc === e.line ? acc.replace(e.from, e.to) : acc), l);
  return doc.pages.map((p) => p.map((l) => edited(l).replace(/^# /, "")).join("\n"));
}
